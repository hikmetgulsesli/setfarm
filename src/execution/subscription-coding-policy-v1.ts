function invalid(): never { throw new Error('SUBSCRIPTION_CODING_INPUT_INVALID'); }
function data(value: unknown, keys: readonly string[]): Record<string, unknown> {
  if (value === null || typeof value !== 'object' || types.isProxy(value)) invalid();
  const prototype = Object.getPrototypeOf(value);
  if (prototype !== Object.prototype && prototype !== null) invalid();
  const descriptors = Object.getOwnPropertyDescriptors(value), actual = Reflect.ownKeys(descriptors);
  if (actual.length !== keys.length || actual.some(key => typeof key !== 'string' || !keys.includes(key))) invalid();
  const copy: Record<string, unknown> = Object.create(null);
  for (const key of keys) {
    const descriptor = descriptors[key];
    if (!descriptor || !Object.hasOwn(descriptor, 'value')) invalid();
    copy[key] = descriptor.value;
  }
  return copy;
}
function canonicalWorktree(value: unknown): value is string {
  return typeof value === 'string' && value.length >= 1 && value.length <= 1024 && value !== '/'
    && value.startsWith('/') && !value.endsWith('/') && !/[\\\x00-\x1f\x7f]/.test(value)
    && !value.includes('//') && !value.split('/').some(part => part === '.' || part === '..')
    && posix.normalize(value) === value;
}
function freeze<T>(value: T): T {
  if (value !== null && typeof value === 'object') {
    for (const child of Object.values(value)) freeze(child);
    Object.freeze(value);
  }
  return value;
}

/** Pure policy data. Filesystem ownership, sandboxing and runtime admission remain the caller's responsibility. */
export function buildSubscriptionCodingMaterialV1(
  input: SubscriptionAttemptLaunchInputV1 & Readonly<{ worktree: string }>,
): SubscriptionCodingMaterialV1 {
  try {
    const value = data(input, ['identity', 'worker', 'root', 'prompt', 'worktree']);
    const identity = data(value.identity, ['attemptId', 'generationId', 'modelRef']);
    const worker = data(value.worker, ['attemptId', 'generationId', 'modelRef', 'providerId', 'modelId',
      'baseUrl', 'api', 'apiKey', 'auth', 'authHeader']);
    const root = value.root, worktree = value.worktree;
    if (typeof root !== 'string' || !canonicalWorktree(worktree)) invalid();
    // Only copied, plain own data enters the existing identity/capability/config validator.
    const base = buildSubscriptionAttemptLaunchMaterialV1({
      identity: { attemptId: identity.attemptId, generationId: identity.generationId, modelRef: identity.modelRef },
      worker: { attemptId: worker.attemptId, generationId: worker.generationId, modelRef: worker.modelRef,
        providerId: worker.providerId, modelId: worker.modelId, baseUrl: worker.baseUrl, api: worker.api,
        apiKey: worker.apiKey, auth: worker.auth, authHeader: worker.authHeader },
      root, prompt: value.prompt,
    } as SubscriptionAttemptLaunchInputV1);
    if (root === worktree || root.startsWith(worktree + '/') || worktree.startsWith(root + '/')) invalid();
    // This JSON body was generated by the owned readonly builder, never supplied by the caller.
    const config = JSON.parse(base.files[0].contents);
    config.agents.defaults.workspace = worktree;
    config.agents.list[0].workspace = worktree;
    config.agents.defaults.timeoutSeconds = 1800;
    config.models.providers[base.identity.modelRef === 'kimi/k3.1-pro' ? 'kimi' : 'minimax'].models[0].maxTokens = 8192;
    config.tools.allow = ['read', 'write', 'edit'];
    const argv = [...base.argv];
    argv[argv.length - 1] = '1800';
    return freeze({ schema: base.schema, profile: 'subscription-coding-files-v1',
      identity: { ...base.identity }, sessionId: base.sessionId, cwd: worktree,
      directories: [...base.directories],
      files: base.files.map((file, index) => ({ path: file.path, mode: file.mode,
        contents: index === 0 ? JSON.stringify(config, null, 2) + '\n' : file.contents })),
      // The isolated worker must not load the host's OpenSSL configuration.
      // Certificate verification and the parent broker's TLS settings stay default.
      env: { ...base.env, OPENSSL_CONF: '/dev/null' }, argv,
    });
  } catch { invalid(); }
}
